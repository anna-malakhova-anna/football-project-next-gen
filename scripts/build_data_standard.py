"""Render the field table of docs/data-standard.md from the p5_data_standard seed (between the fields markers), so the doc and the validation can never drift.

  uv run python -m scripts.build_data_standard          # rewrite the table
  uv run python -m scripts.build_data_standard --check  # exit 1 if the committed doc is out of date
"""
from __future__ import annotations

import csv
import sys
from scripts.common import ROOT

SEED = ROOT / "dbt" / "seeds" / "data_standard_fields.csv"
DOC = ROOT / "docs" / "data-standard.md"
START, END = "<!-- fields:start (generated by scripts/build_data_standard.py from dbt/seeds/data_standard_fields.csv) -->", "<!-- fields:end -->"


def render() -> str:
    with open(SEED, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))
    out = ["| # | Field | Required | Definition and format | Serves | PII | Retention | Evidence for its granularity | Why we ask |", "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        fmt = r["allowed_values"].replace("|", ", ") if r["allowed_values"] else r["format"]
        out.append(f"| {r['ordinal']} | `{r['field_name']}` | {r['requirement'].title()} | {r['definition']}. {fmt} | {r['purposes'].replace('|', ', ')} | {r['pii_class']} | {r['retention_rule']} | {r['evidence']} | {r['rationale']} |")
    return "\n".join(out)


def apply(text: str) -> str:
    a, b = text.index(START), text.index(END)
    return text[:a] + START + "\n" + render() + "\n" + text[b:]


if __name__ == "__main__":
    current = DOC.read_text(encoding="utf-8")
    new = apply(current)
    if "--check" in sys.argv:
        sys.exit(0 if new == current else 1)
    DOC.write_text(new, encoding="utf-8")
