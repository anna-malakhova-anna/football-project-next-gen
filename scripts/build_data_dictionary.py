"""Generate docs/data_dictionary.md from dbt/models/intermediate/_intermediate.yml.

Descriptions and metadata live in the YAML (single source). dbt enforces a model contract on
int_registrations_unioned, so the column names and types in the YAML cannot drift from the built table.
`tests/test_data_dictionary.py` fails if the committed markdown differs from this script's output.
"""
from __future__ import annotations

from pathlib import Path

import yaml
from scripts.common import ROOT

YAML_PATH = ROOT / "dbt" / "models" / "intermediate" / "_intermediate.yml"
OUT_PATH = ROOT / "docs" / "data_dictionary.md"
SYSTEMS = ["US_LEAGUE", "CA_CLUB", "INTL_FED"]


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def render(yaml_path: Path = YAML_PATH) -> str:
    model = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))["models"][0]
    cols = model["columns"]
    business = [c for c in cols if c["meta"]["group"] == "business"]
    helpers = [c for c in cols if c["meta"]["group"] == "helper"]

    def section(title: str, items: list[dict]) -> list[str]:
        lines = [f"## {title}", "",
                 "| Column | Type | Nullable | PII classification | Definition | Derivation |",
                 "|---|---|---|---|---|---|"]
        for c in items:
            m = c["meta"]
            lines.append(f"| `{c['name']}` | {_cell(c['data_type'])} | {_cell(m['nullable'])} | {_cell(m['pii'])} "
                         f"| {_cell(c['description'])} | {_cell(m['derivation'])} |")
        lines += ["", f"### Source mapping: {title.lower()}", "",
                  "| Column | " + " | ".join(SYSTEMS) + " |", "|---|" + "---|" * len(SYSTEMS)]
        for c in items:
            sm = c["meta"]["source_mapping"]
            lines.append(f"| `{c['name']}` | " + " | ".join(_cell(sm[s]) for s in SYSTEMS) + " |")
        lines.append("")
        return lines

    out = [
        "# Data dictionary: `int_registrations_unioned`",
        "",
        "> **All data is synthetic.** This file is generated by `scripts/build_data_dictionary.py` from",
        "> `dbt/models/intermediate/_intermediate.yml`. Edit the YAML, then run `make docs`. Do not edit by hand.",
        "",
        model["description"].strip(),
        "",
        "Grain: one row per registration record, across `US_LEAGUE`, `CA_CLUB` and `INTL_FED`. A person who",
        "registers several times appears several times; this model does **not** resolve identity (Phase 2).",
        "",
        "**PII classes.** *Direct identifier*: identifies a person on its own (names, contact details, a persistent",
        "person id). *Quasi-identifier*: identifies a person in combination (date of birth, postal code, sex,",
        "organization, timestamps). *Non-PII*: not identifying by itself. Consent flags are personal preferences and",
        "are classed Non-PII only in the identifiability sense; they are sensitive once linked to a person. Every",
        "record here is a minor or an adult in a **synthetic** population; in a real deployment, `is_minor` rows",
        "need the strictest handling (Phase 3).",
        "",
        "**Types.** Types are enforced by a dbt model contract. `country_code` and `sex` are documented as 2- and",
        "1-character codes; DuckDB stores them as `VARCHAR` without length enforcement.",
        "",
    ]
    out += section("Business columns", business)
    out += section("Lineage and data-quality helper columns", helpers)
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
