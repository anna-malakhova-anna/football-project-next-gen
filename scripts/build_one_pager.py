"""Build docs/product/one-pager.pdf (the one-page summary printed to one US Letter landscape page) and docs/product/one-pager-copy.md (every copy string, for Anna's approval).

  uv run python -m scripts.build_one_pager        (run `make site` first; this is `make one-pager`)

Playwright drives the installed Chrome, as in the site check. The PDF is not rebuilt by `make product` (a PDF carries its creation time, so every build would show as a change);
scripts/check_one_pager.py checks that the committed file is one Letter landscape page.
"""
from __future__ import annotations

import sys

import yaml
from playwright.sync_api import sync_playwright

from scripts import site_summary
from scripts.check_one_pager import PDF, SLUG, pdf_ok
from scripts.site_shots import ROOT, serve
from scripts.check_one_pager import SITE

COPY_OUT = ROOT / "docs" / "product" / "one-pager-copy.md"


def copy_review(c: dict, status: str) -> str:
    rows = "\n".join(f"| `{k}` | {t.replace('|', '/')} | [ ] approve &nbsp; [ ] edit: |" for k, t in site_summary.copy_strings(c))
    return ("# One-page summary: copy for approval\n\n"
            f"Generated by `scripts/build_one_pager.py` from `summary:` in `site_src/copy/charts.yml`. Status: `{status}`. **Anna approves or edits each string**, then sets `status: final`. "
            "`{placeholders}` are filled from the product-tab exports at build time (the number is never typed here).\n\n"
            "| Key | Text | Approve / edit |\n|---|---|---|\n" + rows + "\n")


def main() -> int:
    if not (SITE / f"{SLUG}.html").exists():
        print("run make public first", file=sys.stderr)
        return 1
    srv, base = serve(SITE)
    try:
        with sync_playwright() as pw:
            browser = pw.chromium.launch(channel="chrome")
            page = browser.new_page(viewport={"width": 1440, "height": 900})
            page.emulate_media(color_scheme="light")
            page.goto(f"{base}/{SLUG}.html")
            page.wait_for_load_state("networkidle")
            page.wait_for_timeout(500)
            pdf = page.pdf(prefer_css_page_size=True, print_background=True)
            browser.close()
    finally:
        srv.shutdown()
    problems = pdf_ok(pdf, "one-pager.pdf")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1
    PDF.parent.mkdir(parents=True, exist_ok=True)
    PDF.write_bytes(pdf)
    c = yaml.safe_load((ROOT / "site_src" / "copy" / "charts.yml").read_text(encoding="utf-8"))["summary"]
    COPY_OUT.write_text(copy_review(c, c.get("status", "?")), encoding="utf-8")
    print(f"wrote {PDF.relative_to(ROOT)} (1 page, Letter landscape) and {COPY_OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
