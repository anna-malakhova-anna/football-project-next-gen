-- DP2. One row per in-scope (flag) feed record with every quality fact the rules of dq_rule_registry need, as plain columns: DP1's p5_record_facts (no identity needed) joined to
-- p5_record_identity (the resolved child: uniqueness and agreement across the child's records). The same columns as before the split; nothing here judges a record.
select
    f.feed,
    f.source_record_id,
    i.p5_person_id,
    f.league_group,
    f.league_id,
    f.league_resolution,
    f.season_year,
    f.season_term,
    f.market_id,
    f.has_league,
    f.has_age_signal,
    f.zip_present,
    f.email_present,
    f.has_sex,
    f.dob_status,
    f.dob_in_youth_range,
    f.zip_known,
    f.email_wellformed,
    f.is_exact_duplicate_row,
    i.is_first_of_child_season,
    f.registered_at,
    f.days_after_season_start,
    f.late_days,
    f.league_current,
    i.dob_consistent,
    i.sex_consistent,
    i.zip3_consistent,
    i.age_group_consistent,
    f.has_consent_record,
    f.has_consent_ts,
    f.has_consent_version,
    f.consent_wording_known
from {{ ref('p5_record_facts') }} f
join {{ ref('p5_record_identity') }} i on i.feed = f.feed and i.source_record_id = f.source_record_id
