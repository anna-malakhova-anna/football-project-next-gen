"""Generate all synthetic source files + quarantined ground truth. Deterministic (seed in config)."""
from __future__ import annotations

from pathlib import Path

import csv

import pyarrow as pa
import pyarrow.parquet as pq

from generator import population
from generator.sources import ca_club, fan, intl_federation, school, us_league

SYNTHETIC_NOTE = "SYNTHETIC DATA: every record is fake; generated by counting-flag-football."


def run(cfg: dict | None = None, raw_dir: str | None = None, truth_dir: str | None = None) -> dict:
    cfg = cfg or population.load_config()
    raw = Path(raw_dir or cfg["paths"]["raw_dir"])
    truth_out = Path(truth_dir or cfg["paths"]["ground_truth_dir"])
    people, parts = population.build_population(cfg)
    population.write_ground_truth(people, parts, truth_out)

    outputs = []
    for module in (us_league, ca_club, intl_federation, school, fan):
        out = module.generate(people, parts, cfg)
        module.write(out, raw)
        outputs.append(out)
    truth = [t for o in outputs for t in o.truth]
    manifest = [m for o in outputs for m in o.manifest]
    for m in manifest:
        m.setdefault("mechanism", None)           # the injected mechanism per record (org profile, missing-not-at-random pattern); evaluation only
    pq.write_table(pa.Table.from_pylist(truth), truth_out / "registration_truth.parquet")
    pq.write_table(pa.Table.from_pylist(manifest), truth_out / "defect_manifest.parquet")
    # aggregate-source truth: program-year totals with the true overlap, and the overlapping people (ground truth; evaluation only)
    school_out = next(o for o in outputs if o.source_system == "SCHOOL_AGGREGATES")
    pq.write_table(pa.Table.from_pylist(school_out.extra["school_truth"]), truth_out / "school_truth.parquet")
    pq.write_table(pa.Table.from_pylist(school_out.extra["school_overlap"]), truth_out / "school_overlap_truth.parquet")
    fan_out = next(o for o in outputs if o.source_system == "FAN_ENGAGEMENT")
    pq.write_table(pa.Table.from_pylist(fan_out.extra["fan_truth"]), truth_out / "fan_truth.parquet")
    pq.write_table(pa.Table.from_pylist(fan_out.extra["fan_account_truth"]), truth_out / "fan_account_truth.parquet")
    pq.write_table(pa.Table.from_pylist(fan_out.extra["fan_market_truth"]), truth_out / "fan_market_truth.parquet")
    pq.write_table(pa.Table.from_pylist(fan_out.extra["fan_consent_truth"]), truth_out / "fan_consent_truth.parquet")
    pq.write_table(pa.Table.from_pylist(fan_out.extra["fan_effect_truth_rows"]), truth_out / "fan_effect_truth.parquet")
    # the true per-season churn probabilities by age (ground truth; evaluation only): what the retention curves are graded against.
    # `churn_p` applies to a player who was active the season before; people who are minors cannot continue past the youth age range.
    pq.write_table(pa.Table.from_pylist([{"min_age": b["min_age"], "max_age": b["max_age"], "churn_p": float(b["p"]),
                                          "youth_max_age": cfg["population"]["youth_age_range"][1]}
                                         for b in cfg["participation"]["churn_by_age"]]), truth_out / "churn_truth.parquet")
    # ---- structured quality (phase 5 spec section 3): org profiles and dark organizations ----
    structured = [o for o in outputs if "orgs" in o.extra]
    orgs = [g for o in structured for g in o.extra["orgs"]]
    pq.write_table(pa.Table.from_pylist(orgs), truth_out / "org_quality_truth.parquet")                 # the latent profile of every org: ground truth
    pq.write_table(pa.Table.from_pylist([u for o in structured for u in o.extra["unreported"]]), truth_out / "unreported_participation_truth.parquet")
    # the org registry is RAW (what the program knows): every known organization, every season, and whether it sent a file. It carries the channel, never the profile.
    with open(raw / "org_registry.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh, lineterminator="\n")
        w.writerow(["org_id", "source_system", "org_name", "region_code", "zip3", "channel", "season_year", "reports_data"])
        for o in structured:
            dark = o.extra["dark"]
            for g in o.extra["orgs"]:
                for y in cfg["seasons"]["years"]:
                    w.writerow([g["org_id"], g["source_system"], g["org_name"], g["region_code"], g["zip3"], g["channel"], y, "N" if g["org_id"] in dark[y] else "Y"])
    (raw / "README_SYNTHETIC.txt").write_text(SYNTHETIC_NOTE + "\n")
    return {"people": len(people), "outputs": outputs}


if __name__ == "__main__":
    res = run()
    print(f"{res['people']} synthetic people;",
          {o.source_system: o.n_records for o in res["outputs"]}, "rows")
